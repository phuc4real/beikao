// Bundle the game engine + GameAuthority + protocol (and zod) into a single
// ESM module that Supabase Edge Functions (Deno) can import cleanly. This is
// the robust alternative to Deno resolving the app's extensionless/`@/` TS
// imports directly. Run `npm run build:functions` before serving/deploying.
import { build } from 'esbuild';
import { resolve } from 'node:path';

const outfile = resolve('supabase/functions/_shared/engine.bundle.js');

await build({
  entryPoints: [resolve('scripts/functions-engine-entry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser', // engine uses only Web APIs (crypto, TextEncoder) — all present in Deno
  target: 'es2022',
  alias: { '@': resolve('src') }, // mirror the Vite/tsconfig '@/' → src/ alias
  outfile,
  legalComments: 'none',
  banner: {
    js: '// AUTO-GENERATED by `npm run build:functions` from src/. Do not edit by hand.',
  },
});

console.log(`built ${outfile}`);
